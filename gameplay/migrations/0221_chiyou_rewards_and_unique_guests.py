def sync_chiyou_rewards(apps, schema_editor):
    database = schema_editor.connection.alias
    ItemTemplate = apps.get_model("gameplay", "ItemTemplate")
    GuestTemplate = apps.get_model("guests", "GuestTemplate")
    WorldUniqueGuest = apps.get_model("guests", "WorldUniqueGuest")
    stored_images = {}
    for target, relative_source in IMAGE_SOURCES.items():
        stored_target = str(Path(target).with_suffix(".webp"))
        if default_storage.exists(stored_target):
            stored_images[target] = stored_target
        else:
            source = Path(settings.BASE_DIR) / "data" / "images" / relative_source
            size = (200, 200) if target.startswith("items/") else (400, 400)
            content, _ = compress_and_resize_image(source, max_size=size, quality=85, convert_to_webp=True)
            stored_images[target] = default_storage.save(stored_target, content)
    for key, data in ITEM_DEFAULTS.items():
        defaults = deepcopy(data)
        defaults["image"] = stored_images[defaults["image"]]
        ItemTemplate.objects.using(database).update_or_create(key=key, defaults=defaults)
    for key, data in GUEST_DEFAULTS.items():
        defaults = deepcopy(data)
        defaults["avatar"] = stored_images[defaults["avatar"]]
        guest, _ = GuestTemplate.objects.using(database).update_or_create(key=key, defaults=defaults)
        WorldUniqueGuest.objects.using(database).get_or_create(template=guest, defaults={"status": "wild"})
    transaction.on_commit(lambda: cache.delete("battle:guest_templates"), using=database, robust=True)


