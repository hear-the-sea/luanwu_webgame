def is_technology_route_complete(route: dict[str, Any], levels: Mapping[str, int]) -> bool:
    """暂未开放的节点不计入路线完成条件。"""
    return all(levels.get(node["key"], 0) >= node["max_level"] for node in route["nodes"] if node["enabled"])
