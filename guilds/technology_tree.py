def _node(
    key: str,
    name: str,
    description: str,
    max_level: int,
    icon_index: int,
    *,
    requires: tuple[str, ...] = (),
    cost: dict[str, int],
    curve: str = "research_3",
    effect: str = "",
    effect_per_level: int = 0,
    production: bool = False,
    production_interval_days: int = 1,
    enabled: bool = True,
) -> dict[str, Any]:
    return {
        "key": key,
        "name": name,
        "description": description,
        "max_level": max_level,
        "icon_index": icon_index,
        "requires": requires,
        "cost": cost,
        "curve": curve,
        "effect": effect,
        "effect_per_level": effect_per_level,
        "production": production,
        "production_interval_days": max(1, int(production_interval_days)),
        "enabled": enabled,
    }


def _cavalry_stat_node(key: str, label: str, icon_index: int) -> dict[str, Any]:
    _stat, per_level, max_level = CAVALRY_STAT_TECHS[key]
    percent = round(per_level * 100)
    return _node(
        key,
        f"嗜血铁骑·{label}",
        f"提高嗜血铁骑{label}，每级提升 {percent}%，最高 {max_level} 级。",
        max_level,
        icon_index,
        requires=("wolf_bloodthirsty_cavalry",),
        cost={"silver": 50000, "grain": 60000, "gold_bar": 1},
        curve="cavalry_10",
        effect=f"嗜血铁骑{label}加成",
        effect_per_level=percent,
    )


